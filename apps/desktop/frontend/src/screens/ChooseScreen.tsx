/**
 * SavedChoices is the old preset bar, folded into a menu: applying one is
 * occasional, so it no longer takes a row of the screen. Renaming and deleting
 * are in Settings.
 */
function SavedChoices({
  presets,
  active,
  options,
  onApply,
  onChanged,
}: {
  presets: presetModels.Preset[] | null;
  active: string;
  options: core.Options;
  onApply: (preset: presetModels.Preset) => void;
  onChanged: () => void;
}) {
  const [naming, setNaming] = useState(false);
  const [name, setName] = useState("");
  const [error, setError] = useState("");

  async function save() {
    setError("");
    try {
      await api.SavePreset(name.trim(), options);
      setName("");
      setNaming(false);
      onChanged();
    } catch (e) {
      setError(cleanError(e));
    }
  }

  if (naming) {
    return (
      <div className="flex items-center gap-xs">
        {error && <span className="text-body-sm text-danger-strong">{error}</span>}
        <Input
          autoFocus
          value={name}
          placeholder="Name these choices"
          aria-label="Name for these choices"
          className="w-52"
          onChange={(e) => setName(e.target.value)}
          onKeyDown={(e) => {
            if (e.key === "Enter" && name.trim()) void save();
            if (e.key === "Escape") {
              e.preventDefault();
              e.stopPropagation();
              setNaming(false);
            }
          }}
        />
        <Button size="sm" variant="primary" disabled={!name.trim()} onClick={() => void save()}>
          Save
        </Button>
        <Button size="sm" variant="tertiary" onClick={() => setNaming(false)}>
          Cancel
        </Button>
      </div>
    );
  }

  return (
    <div className="flex items-center gap-xxs">
      <Dropdown
        className="w-48"
        ariaLabel="Saved choices"
        placeholder="Saved choices"
        value={active}
        options={(presets ?? []).map((p) => ({ value: p.id, label: p.name }))}
        onChange={(id) => {
          const preset = presets?.find((p) => p.id === id);
          if (preset) onApply(preset);
        }}
      />
      <Button size="sm" variant="tertiary" onClick={() => setNaming(true)}>
        Save these…
      </Button>
    </div>
  );
}

/** PLAYLIST_ROW_HEIGHT is fixed so a long playlist can be virtualised. */
const PLAYLIST_ROW_HEIGHT = 40;

/** PlaylistPicker is the list of a playlist's videos, each one to tick. */
function PlaylistPicker({
  entries,
  selected,
  onChange,
}: {
  entries: core.Entry[];
  selected: Set<number>;
  onChange: (next: Set<number>) => void;
}) {
  const indexed = useMemo(() => entries.map((entry, index) => ({ entry, index })), [entries]);
  const all = selected.size === entries.length;

  function toggle(index: number) {
    const next = new Set(selected);
    if (next.has(index)) next.delete(index);
    else next.add(index);
    onChange(next);
  }

  return (
    <section className="flex flex-col gap-xs">
      <div className="flex items-center justify-between gap-sm">
        <Eyebrow>Videos</Eyebrow>
        <div className="flex items-center gap-xs">
          <span className="text-body-sm text-ink-subtle tabular-nums">
            {selected.size} of {entries.length} chosen
          </span>
          <Button
            size="sm"
            variant="tertiary"
            onClick={() => onChange(all ? new Set() : new Set(entries.map((_, i) => i)))}
          >
            {all ? "Choose none" : "Choose all"}
          </Button>
        </div>
      </div>
      <div
        className="flex flex-col overflow-hidden rounded-md border border-hairline"
        style={{ height: Math.min(entries.length, 8) * PLAYLIST_ROW_HEIGHT + 2 }}
      >
        <VirtualList
          items={indexed}
          rowHeight={PLAYLIST_ROW_HEIGHT}
          getKey={(row) => String(row.index)}
          className="min-h-0 flex-1"
          renderRow={({ entry, index }) => (
            <label
              className="no-drag flex cursor-pointer items-center gap-sm border-b border-surface-3 px-sm hover:bg-surface-1"
              style={{ height: PLAYLIST_ROW_HEIGHT }}
            >
              <input
                type="checkbox"
                checked={selected.has(index)}
                onChange={() => toggle(index)}
                className="size-4 shrink-0 cursor-pointer accent-primary"
                aria-label={entry.title || `Video ${index + 1}`}
              />
              <span className="w-8 shrink-0 text-right text-body-sm text-ink-tertiary tabular-nums">{index + 1}</span>
              <span className="min-w-0 flex-1 truncate text-body-sm text-ink" title={entry.title}>
                {entry.title || entry.url}
              </span>
              <span className="shrink-0 text-body-sm text-ink-subtle tabular-nums">
                {formatDuration(entry.duration)}
              </span>
            </label>
          )}
        />
      </div>
    </section>
  );
}

/** MoreOptions holds everything yt-dlp can do that the screen does not show. */
function MoreOptions({
  open,
  onOpenChange,
  options,
  url,
  onChange,
}: {
  open: boolean;
  onOpenChange: (open: boolean) => void;
  options: core.Options;
  url: string;
  onChange: (next: core.Options) => void;
}) {
  const [command, setCommand] = useState("");
  const [error, setError] = useState("");

  useEffect(() => {
    if (!open) {
      setCommand("");
      setError("");
    }
  }, [open]);

  async function showCommand() {
    setError("");
    try {
      setCommand(await api.ShowCommand({ ...options, url } as core.Options));
    } catch (e) {
      setError(cleanError(e));
    }
  }

  return (
    <Sheet
      open={open}
      onOpenChange={onOpenChange}
      title="More options"
      description="These apply to this download and are kept for the next one."
    >
      <div className="flex min-h-0 flex-col overflow-y-auto">
        <AdvancedDrawer bare options={options} onChange={onChange} onRequestClose={() => onOpenChange(false)} />
        <div className="flex flex-col gap-xs border-t border-hairline px-md py-sm">
          {command ? (
            <>
              <Eyebrow>The yt-dlp command</Eyebrow>
              <MonoBlock text={command} copyable />
              <p className="text-caption text-ink-tertiary">
                Progress-reporting flags are left out; they change what yt-dlp prints, not the file.
              </p>
            </>
          ) : (
            <div>
              <Button
                size="sm"
                variant="tertiary"
                onClick={() => void showCommand()}
                icon={<Icon.Command className="size-3.5" strokeWidth={1.75} aria-hidden />}
              >
                Show the yt-dlp command
              </Button>
            </div>
          )}
          {error && <p className="text-body-sm text-danger-strong">{error}</p>}
        </div>
      </div>
    </Sheet>
  );
}

/**
 * ResolveError is a link that did not resolve, with the way forward. When the
 * reason looks like Lasso's own setup rather than the site's answer, that
 * includes the doctor, by the same rule a failed download uses.
 */
function ResolveError({ error, kind, onRetry }: { error: string; kind: string; onRetry: () => void }) {
  const { message, detail } = explain(error);
  const suggests = useSuggestsDoctor(kind);
  const openDoctor = useDoctor();
  return (
    <Banner
      title="That link did not work"
      tone="danger"
      action={
        <div className="flex items-center gap-xs">
          {needsFullDiskAccess(error) && (
            <Button
              size="sm"
              icon={<Icon.Settings className="size-3.5" strokeWidth={1.75} aria-hidden />}
              onClick={() => void api.OpenFullDiskAccessSettings()}
            >
              Open System Settings
            </Button>
          )}
          {suggests && (
            <Button
              size="sm"
              icon={<Icon.Doctor className="size-3.5" strokeWidth={1.75} aria-hidden />}
              onClick={openDoctor}
            >
              Diagnose
            </Button>
          )}
          <Button
            size="sm"
            icon={<Icon.Retry className="size-3.5" strokeWidth={1.75} aria-hidden />}
            onClick={onRetry}
          >
            Try again
          </Button>
        </div>
      }
    >
      {message}
      {detail && (
        // yt-dlp's own words stay reachable but never lead: the sentence above
        // is the one that says what to do.
        <Details summary="Details">
          <MonoBlock text={detail} maxHeight="10rem" copyable />
        </Details>
      )}
    </Banner>
  );
}

