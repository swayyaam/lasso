// ---- The choices ----

function videoChoices(quality?: core.QualityOptions): Choice[] {
  if (!quality?.hasVideo) return [];

  const best: Choice = {
    pick: "best",
    label: "Best",
    detail: quality.approximate ? "" : quality.bestLabel,
    note: "Recommended",
    hint:
      !quality.approximate && quality.bestLabel && !quality.bestPlayable
        ? "Needs IINA or VLC: nothing this Mac plays was offered."
        : undefined,
    bytes: quality.bestBytes,
  };

  const tiers = (quality.tiers ?? [])
    // Best already stands for its own rung; listing it twice would only ask
    // which of two identical rows to pick.
    .filter((tier) => quality.approximate || tier.height !== quality.bestHeight)
    .map<Choice>((tier) => ({
      pick: `${tier.height}p`,
      label: tier.label,
      detail: tier.detail,
      tags: <TierTags tier={tier} />,
      hint: quality.approximate || tier.playable ? undefined : "Needs IINA or VLC to play on this Mac.",
      bytes: tier.bytes,
    }));

  return [best, ...tiers];
}

function audioChoices(quality?: core.QualityOptions): Choice[] {
  if (quality && !quality.hasAudio) return [];
  const size = (pick: string) => quality?.audioSizes?.[pick];

  const list: Array<Omit<Choice, "bytes" | "estimate">> = [
    { pick: "audio-original", label: "Original", note: "Recommended", hint: "The site's own audio, untouched." },
    { pick: "audio-m4a", label: "M4A", hint: "What Music and iPhone use." },
    { pick: "audio-mp3", label: "MP3", hint: "Plays anywhere. Converted, so a little is lost." },
    { pick: "audio-opus", label: "Opus", hint: "Smallest for the same sound; not every player opens it." },
    {
      pick: "audio-flac",
      label: "FLAC",
      hint: quality?.losslessAudio
        ? "Lossless, from a lossless source."
        : "Bigger, not better: this source is already compressed.",
    },
  ];
  return list.map((c) => ({ ...c, bytes: size(c.pick)?.bytes ?? 0, estimate: size(c.pick)?.estimate ?? false }));
}

function TierTags({ tier }: { tier: core.ResolutionTier }) {
  if (!tier.hasHDR && !tier.hasHighFrameRate) return null;
  return (
    <span className="flex gap-xxs">
      {tier.hasHDR && (
        <Tag tone="purple" title={`High dynamic range (${tier.hdrFormat || "HDR"})`}>
          {tier.hdrFormat || "HDR"}
        </Tag>
      )}
      {tier.hasHighFrameRate && (
        <Tag tone="blue" title="60 frames a second or more">
          60 fps
        </Tag>
      )}
    </span>
  );
}

/** validPick keeps a pick that this link can honour, and replaces one it cannot. */
function validPick(pick: string, quality?: core.QualityOptions): string {
  if (!quality) return pick || "best";
  if (pick?.startsWith("audio-")) return quality.hasAudio ? pick : "best";
  if (!quality.hasVideo) return "audio-original";
  if (!pick || pick === "best") return "best";
  return (quality.tiers ?? []).some((t) => `${t.height}p` === pick) ? pick : "best";
}

function sizeText(choice?: Choice): string {
  const text = choice ? formatBytes(choice.bytes) : "";
  if (!text) return "";
  return choice?.estimate ? `~${text}` : text;
}

function downloadLabel(playlist: boolean, count: number, current?: Choice): string {
  if (playlist) return count === 1 ? "Download 1 video" : `Download ${count} videos`;
  const size = sizeText(current);
  return size ? `Download · ${size}` : "Download";
}

/** footnote says what the chosen file will be, in terms of what opens it. */
function footnote(kind: Kind, options: core.Options, quality?: core.QualityOptions, current?: Choice): string {
  if (kind === "audio") {
    return options.pick === "audio-original"
      ? "Kept as the site sent it, usually M4A or Opus, with nothing converted."
      : "Converted by ffmpeg once the download finishes.";
  }
  if (options.container || options.videoCodec) {
    return "Saved in the format set in More options.";
  }
  if (quality?.approximate) {
    return "Each video is saved as MP4 where it can be, which QuickTime, Quick Look and Photos open.";
  }
  if (current?.hint) {
    return "That quality only comes in a format QuickTime cannot open. IINA and VLC play it; Best is the largest that plays here.";
  }
  return "Saved as MP4, which QuickTime, Quick Look, Photos and iMovie open.";
}
